let LANG = "en";

function setLanguage(lang) {
  LANG = lang === "ru" ? "ru" : "en";
  document.documentElement.lang = LANG;
}

// t("key", { name: "x" }) — the string for the current language with {name} filled in.
function t(key, vars = {}) {
  const text = STRINGS[LANG][key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

// "3 models" / "3 модели" with the right plural form.
function modelWord(count) {
  const forms = {
    ru: { one: "модель", few: "модели", many: "моделей", other: "модели" },
    en: { one: "model", other: "models" },
  }[LANG];
  const rule = new Intl.PluralRules(LANG).select(count);
  return `${count} ${forms[rule] ?? forms.other}`;
}

function nodeWord(count) {
  const forms = {
    ru: { one: "узел", few: "узла", many: "узлов", other: "узла" },
    en: { one: "node", other: "nodes" },
  }[LANG];
  const rule = new Intl.PluralRules(LANG).select(count);
  return `${count} ${forms[rule] ?? forms.other}`;
}

// Fills elements marked data-i18n (text), data-i18n-html (trusted markup from STRINGS),
// data-i18n-title, data-i18n-placeholder and data-i18n-aria.
function applyI18n(root = document) {
  for (const node of root.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll("[data-i18n-html]")) node.innerHTML = t(node.dataset.i18nHtml);
  for (const node of root.querySelectorAll("[data-i18n-title]")) node.title = t(node.dataset.i18nTitle);
  for (const node of root.querySelectorAll("[data-i18n-placeholder]")) {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  }
  for (const node of root.querySelectorAll("[data-i18n-aria]")) {
    node.setAttribute("aria-label", t(node.dataset.i18nAria));
  }
}
